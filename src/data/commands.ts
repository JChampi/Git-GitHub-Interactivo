/** Comandos del diccionario indexados por clave (incluye alias razonables). */
export function docFor(topic: string | undefined): CommandDoc | undefined {
  if (!topic) return undefined;
  const t = topic.trim();
  const direct = COMMANDS.find((c) => c.key === t);
  if (direct) return direct;
  const map: Record<string, string> = { git: 'git help', code: 'nano', vim: 'nano', vi: 'nano', edit: 'nano', editor: 'nano', 'gh pr': 'gh pr create', 'gh issue': 'gh issue create', 'gh repo': 'gh repo create', 'gh pr list': 'gh pr create', 'gh pr view': 'gh pr create', 'gh pr close': 'gh pr merge' };
  return COMMANDS.find((c) => c.key === map[t]);
}

